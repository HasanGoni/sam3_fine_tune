"""Mechanical repo rules (see CODING_STANDARDS.md): cheap, stdlib-only, run in CI and by pre-commit."""

import re
from pathlib import Path

REPO = Path(__file__).parents[1]
SCANNED = ("sam3_fine_tune", "scripts", "tests")
# Vendored upstream code that pickles arbitrary Python objects between ranks.
UNSAFE_LOAD_ALLOWED_FILES = {"sam3/train/utils/distributed.py"}
UNSAFE_LOAD_MARKER = "unsafe-load-ok"


def _py_files(roots):
    for root in roots:
        yield from (REPO / root).rglob("*.py")


def test_torch_load_never_disables_weights_only_without_a_reason():
    """`weights_only=False` unpickles arbitrary code; justify it with `# unsafe-load-ok: <why>` on the same line."""
    offenders = []
    for path in _py_files(SCANNED + ("sam3",)):
        rel = path.relative_to(REPO).as_posix()
        if rel in UNSAFE_LOAD_ALLOWED_FILES or rel == "tests/test_repo_standards.py":
            continue
        for n, line in enumerate(path.read_text().splitlines(), 1):
            if "weights_only=False" in line and UNSAFE_LOAD_MARKER not in line:
                offenders.append(f"{rel}:{n}")
    assert not offenders, f"torch.load(weights_only=False) without '# {UNSAFE_LOAD_MARKER}: <reason>': {offenders}"


# the one place the flag is derived from a caller's `trusted` argument (default False), allow-listed explicitly
WEIGHTS_ONLY_NOT_TRUSTED = (
    "sam3_fine_tune/inference/run.py",
    'checkpoint, map_location="cpu", weights_only=not trusted',
)


def test_weights_only_is_always_the_literal_true():
    """Any other `weights_only=` value (False, a variable, a config key) can unpickle arbitrary code."""
    offenders = []
    for path in _py_files(SCANNED + ("sam3",)):
        rel = path.relative_to(REPO).as_posix()
        if rel in UNSAFE_LOAD_ALLOWED_FILES or rel == "tests/test_repo_standards.py":
            continue
        lines = path.read_text().splitlines()
        for n, line in enumerate(lines, 1):
            for m in re.finditer(r"weights_only\s*=\s*(\w+(?:\s+\w+)?)", line):
                if m.group(1) == "True":
                    continue
                if rel == WEIGHTS_ONLY_NOT_TRUSTED[0] and line.strip().endswith(
                    "weights_only=not trusted"
                ):
                    continue
                if UNSAFE_LOAD_MARKER in line and m.group(1) == "False":
                    continue  # justified on the same line; see the test above
                offenders.append(f"{rel}:{n}: {line.strip()}")
    assert not offenders, f"weights_only must be the literal True: {offenders}"


def test_every_hydra_conf_folder_is_a_python_package():
    """Hydra resolves `config_path="conf"` as a package; without __init__.py it fails with 'config module not found'."""
    missing = [
        p.relative_to(REPO).as_posix()
        for p in (REPO / "sam3_fine_tune").rglob("conf")
        if p.is_dir()
        and "__pycache__" not in p.parts
        and not (p / "__init__.py").exists()
    ]
    assert not missing, f"add an empty __init__.py to: {missing}"


def test_every_conf_folder_is_listed_as_package_data():
    import tomllib

    package_data = tomllib.loads((REPO / "pyproject.toml").read_text())["tool"][
        "setuptools"
    ]["package-data"]
    conf_packages = {
        ".".join(p.relative_to(REPO).parts[:-1])
        for p in (REPO / "sam3_fine_tune").rglob("conf")
        if p.is_dir() and any(p.glob("*.yaml"))
    }
    missing = sorted(conf_packages - set(package_data))
    assert (
        not missing
    ), f"add [tool.setuptools.package-data] entries (conf/*.yaml) for: {missing}"


def test_autogenerated_modules_are_excluded_from_formatting():
    cfg = (REPO / ".pre-commit-config.yaml").read_text()
    for path in (REPO / "sam3_fine_tune").rglob("*.py"):
        head = path.read_text(errors="ignore")[:400]
        if "AUTOGENERATED" in head and path.parent.name == "inference":
            assert (
                path.name.replace(".", r"\.") in cfg
            ), f"{path.name} is AUTOGENERATED: exclude it in .pre-commit-config.yaml"


def test_every_package_with_a_conf_folder_is_formatted_by_pre_commit():
    """A new CLI package must be added to the ufmt `files:` pattern, or its code is silently left unformatted."""
    import re

    cfg = (REPO / ".pre-commit-config.yaml").read_text()
    match = re.search(r"files: \^\(tests/\|sam3_fine_tune/\(([^)]*)\)", cfg)
    assert match, "the ufmt `files:` pattern changed shape: update this test"
    formatted = set(match.group(1).split("|"))
    missing = sorted(
        p.parent.name
        for p in (REPO / "sam3_fine_tune").glob("*/conf")
        if p.is_dir() and p.parent.name not in formatted
    )
    assert (
        not missing
    ), f"add to the ufmt `files:` pattern in .pre-commit-config.yaml: {missing}"
